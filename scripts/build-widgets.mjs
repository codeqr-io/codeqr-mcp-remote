// Bundles each widget under web/ into one self-contained HTML page and writes
// it to src/widgets/generated/ as a string constant. The generated module is
// committed: Vercel builds api/server.ts by following its imports, so a page
// read from disk at runtime could be left out of the deployment.
//
//   node scripts/build-widgets.mjs          write the generated modules
//   node scripts/build-widgets.mjs --check  fail if they are out of date
//   node scripts/build-widgets.mjs --html   also write web/dev/out/<name>.html for the dev harness

import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const WIDGETS = [
  {
    name: 'item-card',
    entry: 'web/item-card/main.ts',
    styles: 'web/item-card/styles.css',
    output: 'src/widgets/generated/item-card.ts',
    exportName: 'ITEM_CARD_HTML',
  },
  {
    name: 'analytics',
    entry: 'web/analytics/main.ts',
    styles: 'web/analytics/styles.css',
    output: 'src/widgets/generated/analytics.ts',
    exportName: 'ANALYTICS_HTML',
  },
];

async function bundle(entryPoint, loader) {
  const { outputFiles } = await build({
    entryPoints: [entryPoint],
    bundle: true,
    minify: true,
    write: false,
    format: loader === 'css' ? undefined : 'iife',
    target: 'es2020',
    legalComments: 'none',
    charset: 'utf8',
  });
  return outputFiles[0].text.trim();
}

async function page(widget) {
  const script = (await bundle(widget.entry)).replaceAll('</script', '<\\/script');
  const styles = await bundle(widget.styles, 'css');
  return (
    '<!doctype html><html><head><meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width,initial-scale=1">' +
    `<style>${styles}</style></head><body><div id="root"></div><script>${script}</script></body></html>`
  );
}

function module(widget, html) {
  return (
    `// Generated by scripts/build-widgets.mjs from ${widget.entry}. Do not edit: run \`yarn widgets:build\`.\n` +
    `export const ${widget.exportName} = ${JSON.stringify(html)};\n`
  );
}

const check = process.argv.includes('--check');
const html = process.argv.includes('--html');
let stale = 0;

for (const widget of WIDGETS) {
  const built = await page(widget);
  const source = module(widget, built);
  if (check) {
    const current = await readFile(widget.output, 'utf8').catch(() => '');
    if (current !== source) {
      stale++;
      console.error(`${widget.output} is out of date: run \`yarn widgets:build\` and commit it.`);
    }
    continue;
  }
  await writeFile(widget.output, source);
  if (html) {
    await mkdir('web/dev/out', { recursive: true });
    await writeFile(`web/dev/out/${widget.name}.html`, built);
  }
  console.log(`${widget.output}: ${Buffer.byteLength(built)} bytes`);
}

if (stale) process.exit(1);
